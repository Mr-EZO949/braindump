import type { Edge, EdgeType, GraphData, Node, NodeType } from "@/types/graph";

const now = "2026-03-16T00:00:00.000Z";
const demoUserId = "demo-user";
const demoWorkspaceId = "workspace-general";

function getImportanceLabel(score: number) {
  if (score >= 72) {
    return "high";
  }

  if (score >= 45) {
    return "medium";
  }

  return "low";
}

function createNode(
  id: string,
  title: string,
  summary: string,
  rawText: string,
  nodeType: NodeType,
  importanceIndex: number,
  color: string,
): Node {
  return {
    id,
    user_id: demoUserId,
    workspace_id: demoWorkspaceId,
    title,
    summary,
    raw_text: rawText,
    node_type: nodeType,
    importance: getImportanceLabel(importanceIndex),
    importance_index: importanceIndex,
    color,
    created_at: now,
    updated_at: now,
  };
}

function createEdge(
  id: string,
  sourceNodeId: string,
  targetNodeId: string,
  edgeType: EdgeType,
): Edge {
  return {
    id,
    user_id: demoUserId,
    workspace_id: demoWorkspaceId,
    source_node_id: sourceNodeId,
    target_node_id: targetNodeId,
    edge_type: edgeType,
    created_at: now,
  };
}

